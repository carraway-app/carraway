/** Alle Schlüsselpfade eines Textbaums, z. B. `kennzahlen.nav`; Grundlage des Paritätstests. */
export function schluessel(baum: object, vorne = ""): string[] {
  return Object.entries(baum).flatMap(([k, v]) => (typeof v === "object" && v !== null ? schluessel(v, `${vorne}${k}.`) : [`${vorne}${k}`]));
}

