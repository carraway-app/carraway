const KAPITAL_QUELLEN_INTERN = umkehr(KAPITAL_QUELLEN);
const QUELLEN_FELDER = new Set(["id", "quelleId", "quelle", "ref"]);

function kapitalQuelle(wert: string, namen: Record<string, string>) {
  if (wert === "stamm" || wert === "common") return nameAus(namen, wert);
  const trenner = wert.indexOf(":");
  if (trenner === -1) return wert;
  return nameAus(namen, wert.slice(0, trenner)) + wert.slice(trenner);
}

export const kapitalQuelleAnApi = (wert: string) => kapitalQuelle(wert, KAPITAL_QUELLEN);
export const kapitalQuelleVonApi = (wert: string) => kapitalQuelle(wert, KAPITAL_QUELLEN_INTERN);

function grundIstKennung(objekt: object, nachAussen: boolean) {
  const hat = (name: string) => Object.hasOwn(objekt, nachAussen ? name : portfolioFeldAnApi(name));
  return hat("anteileVorherQuelle") || (hat("beteiligungId") && (hat("fehlend") || hat("organisation")));
}

function abbilden(wert: unknown, nachAussen: boolean, feld?: string): unknown {
  if (Array.isArray(wert)) return wert.map((x) => abbilden(x, nachAussen, feld));
  if (typeof wert === "string" && feld) {
    if (feld === "schluessel") return nachAussen ? portfolioMetrikAnApi(wert) : portfolioMetrikVonApi(wert);
    const name = QUELLEN_FELDER.has(feld) ? (nachAussen ? kapitalQuelleAnApi(wert) : kapitalQuelleVonApi(wert)) : wert;
    return ENUM_AN_API.has(feld) ? (nachAussen ? portfolioEnumAnApi(name) : portfolioEnumVonApi(name)) : name;
  }
  if (!wert || typeof wert !== "object" || Object.getPrototypeOf(wert) !== Object.prototype) return wert;
  const objekt = wert;
  return Object.fromEntries(Object.entries(objekt).map(([name, wert]) => {
    const innen = nachAussen ? name : portfolioFeldVonApi(name);
    const aussen = nachAussen ? name === "schluessel" && Array.isArray(wert) ? "metricKeys" : portfolioFeldAnApi(name) : innen;
    if (NUTZERFELDER.has(innen) && !Array.isArray(wert)) return [aussen, wert];
    // Der Grund ist bei Vorschlägen und ausgelassenen Positionen eine Kennung,
    // bei Korrekturen und Stornos hingegen ein frei eingegebener Text.
    if (innen === "grund" && !grundIstKennung(objekt, nachAussen)) return [aussen, wert];
    return [aussen, abbilden(wert, nachAussen, innen)];
  }));
}

export const portfolioAnApi = <T>(wert: T) => abbilden(wert, true) as PortfolioApi<T>;
export const portfolioVonApi = <T>(wert: T) => abbilden(wert, false) as PortfolioIntern<T>;
