/** Fehler zu einem Eingabefeld, wie ihn die Prüfungen intern sammeln. Nach außen geht er als `FieldError` (`fehlerAntwort`). */
export interface Feldfehler {
  /** Name des Feldes, bei verschachtelten Feldern mit Punkt getrennt. */
  feld: string;
  /** Code des Prüfschritts, z. B. `invalid_format` oder `too_big`. */
  code: string;
  meldung: string;
}

/** Feldfehler im Fehlerformat der API (englisch, Entscheidung 520). */
export interface FieldError {
  field: string;
  code: string;
  message: string;
}

/** Einheitliches Fehlerformat der API: `{ error: { code, message, fields?, …weitere Angaben } }`. */
export interface Fehlerantwort {
  error: { code: Fehlercode; message: string; fields?: FieldError[]; [zusatz: string]: unknown };
}

const istFeldfehler = (wert: unknown): wert is Feldfehler =>
  typeof wert === "object" && wert !== null && typeof (wert as Feldfehler).feld === "string" && typeof (wert as Feldfehler).code === "string";

const KONTAKT_PFAD = /^\/api\/v1\/(?:activities|calendar|contact-import|contact-roles|contact-suggestions|crm|custom-fields|dealflow|deals|external|follow-ups|mail|mailbox|meetings|organization-relationships|people|search)(?:\/|$)|^\/api\/v1\/organizations(?:\/[^/]+(?:\/merge(?:\/preview)?)?)?\/?$|^\/api\/v1\/(?:financing-rounds|funds|investments|transactions)\/[^/]+\/(?:fields|instrument-fields)$/;

/** Fachlicher Fehler in einer schreibenden Anfrage: bricht die Transaktion ab und wird zu einer Fehlerantwort. */
export class Fachfehler extends Error {
  constructor(
    readonly status: ContentfulStatusCode,
    readonly code: Fehlercode,
    meldung: string,
    /** Weitere Felder im Fehlerobjekt, z. B. `kandidaten` bei `possible_duplicate`. */
    readonly zusatz?: Record<string, unknown>,
  ) {
    super(meldung);
  }
}

export function fehlerAntwort(
  c: Context,
  status: ContentfulStatusCode,
  code: Fehlercode,
  meldung: string,
  felder?: Feldfehler[],
  zusatz?: Record<string, unknown>,
) {
  // Feldfehler kommen als Parameter (Validatoren) oder als `felder` in den weiteren Angaben eines Fachfehlers.
  const { felder: zusatzFelder, ...rest } = zusatz ?? {};
  const alleFelder = felder ?? (Array.isArray(zusatzFelder) && zusatzFelder.length > 0 && zusatzFelder.every(istFeldfehler) ? zusatzFelder : undefined);
  const weitere = alleFelder === undefined && zusatzFelder !== undefined ? { ...rest, felder: zusatzFelder } : rest;
  const bericht = berichtBereich(c.req.path);
  const kontakt = KONTAKT_PFAD.test(c.req.path);
  const portfolio = c.get("portfolioVertrag");
  const fonds = c.get("fondsVertrag");
  const fields = alleFelder?.map((f): FieldError => {
    let field = f.feld;
    if (bericht) field = berichtFeldpfadAnApi(bericht, field);
    else if (kontakt) field = englischerFeldpfad(field);
    else if (fonds) field = field.split(".").map(fondsFeldAnApi).join(".");
    else if (portfolio) field = field.split(".").map(portfolioFeldAnApi).join(".");
    return { field, code: f.code, message: f.meldung };
  });
  const details = bericht ? berichtAnApi(bericht, weitere) : kontakt ? aufEnglisch(weitere) : fonds ? fondsAnApi(weitere) : portfolio ? portfolioAnApi(weitere) : weitere;
  const koerper: Fehlerantwort = { error: { code, message: meldung, ...(fields ? { fields } : {}), ...details } };
  return c.json(koerper, status);
}

/** Eine zusammengeführte Organisation (oder Person) bleibt als Datensatz erhalten, nimmt aber nichts Neues mehr auf. */
export const bereitsZusammengefuehrtFehler = (zusammengefuehrtIn: string) =>
  new Fachfehler(409, "already_merged", "The record has been merged into another record.", { zusammengefuehrtIn });
