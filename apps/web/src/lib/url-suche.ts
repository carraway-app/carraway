const interneWerte = new Map(Array.from(werte, ([name, ziel]) => [ziel, name]));

function auswahlwert(name: string, wert: unknown, tabelle: Map<string, string>) {
  if (!auswahl.has(name) || typeof wert !== "string") return wert;
  return wert.split(",").map((teil) => tabelle.get(teil) ?? teil).join(",");
}

export function parseSearch(text: string) {
  const suche: Record<string, unknown> = defaultParseSearch(text);
  // Ein Token ist auch dann Text, wenn sein Inhalt wie eine JSON-Zahl aussieht.
  if (Object.hasOwn(suche, "token")) suche.token = new URLSearchParams(text).get("token");
  const eintraege = Object.entries(suche).filter(([name]) => !englisch.has(name));
  return Object.fromEntries(eintraege.map(([name, wert]) => {
    const feld = intern.get(name) ?? name;
    return [feld, auswahlwert(feld, wert, interneWerte)];
  }));
}

export function stringifySearch(suche: Record<string, unknown>) {
  const { token, ...felder } = suche;
  const query = defaultStringifySearch(Object.fromEntries(Object.entries(felder).map(([name, wert]) => [
    englisch.get(name) ?? name, auswahlwert(name, wert, werte),
  ])));
  if (typeof token !== "string") return query;
  return `${query}${query ? "&" : "?"}${new URLSearchParams({ token })}`;
}
